#Requires -Version 7.2
<#
.SYNOPSIS
    Erzeugt die privaten SQL-Eingaben für die begrenzte Windows-Providerabnahme.
.DESCRIPTION
    Provisioniert keinen Run und führt kein SQL aus. Vollständige kanonische
    Quelldateien bleiben beim Aufteilen des Standaloneinstallers zusammen.
    Die erzeugten Eingaben benötigen einen separat gebundenen eigenen Run.
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory)][string]$OutputDirectory,
    [guid]$OperationId = [guid]::NewGuid()
)
Set-StrictMode -Version Latest
$ErrorActionPreference='Stop'
$repositoryRoot=[IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
$destination=[IO.Path]::GetFullPath($OutputDirectory)
if ($OperationId -eq [guid]::Empty) { throw 'OPS005_OPERATION_REQUIRED' }
if ($destination.StartsWith($repositoryRoot.TrimEnd('\','/')+[IO.Path]::DirectorySeparatorChar,[StringComparison]::OrdinalIgnoreCase) -or
    $destination -eq $repositoryRoot) { throw 'OPS005_PRIVATE_OUTPUT_REQUIRED' }
if (Test-Path -LiteralPath $destination) { throw 'OPS005_PREPARATION_ALREADY_EXISTS' }
$head=(& git -C $repositoryRoot rev-parse HEAD).Trim()
if ($LASTEXITCODE -ne 0 -or $head -cnotmatch '^[a-f0-9]{40}$') { throw 'OPS005_SOURCE_BINDING_FAILED' }
$null=[IO.Directory]::CreateDirectory($destination)
$encoding=[Text.UTF8Encoding]::new($false)
function Write-PrivateSql([string]$Name,[string]$Content) {
    $path=Join-Path $destination $Name
    [IO.File]::WriteAllText($path,$Content,$encoding)
    return $path
}

$canonical=Join-Path $destination 'canonical-install.sql'
& (Join-Path $repositoryRoot 'Code/Install/Build-StandaloneInstaller.ps1') -RepositoryRoot $repositoryRoot -OutputPath $canonical
$text=[IO.File]::ReadAllText($canonical,$encoding)
$sections=[regex]::Matches($text,'(?ms)^-- BEGIN SOURCE: (?<path>[^\r\n]+)\r?\n.*?^-- END SOURCE: \k<path>\r?$')
if ($sections.Count -eq 0 -or ($sections | Group-Object { $_.Groups['path'].Value } | Where-Object Count -gt 1)) {
    throw 'OPS005_CANONICAL_SOURCE_BOUNDARY_INVALID'
}
$remainder=[regex]::Replace($text,'(?ms)^-- BEGIN SOURCE: (?<path>[^\r\n]+)\r?\n.*?^-- END SOURCE: \k<path>\r?$','')
if (($remainder -replace '\AUSE \[DeineDatenbank\];\r?\nGO\s*/\* Generated from canonical source files\. Do not edit this file directly\. \*/\s*','').Trim()) {
    throw 'OPS005_CANONICAL_CONTENT_OUTSIDE_SOURCES'
}
$prefix=@'
USE [DeineDatenbank];
GO
SET NOCOUNT ON;
SET XACT_ABORT ON;
SET ANSI_NULLS ON;
SET ANSI_PADDING ON;
SET ANSI_WARNINGS ON;
SET ARITHABORT ON;
SET CONCAT_NULL_YIELDS_NULL ON;
SET NUMERIC_ROUNDABORT OFF;
SET QUOTED_IDENTIFIER ON;
GO
'@+"`n"
$prefix=$prefix.Replace('[DeineDatenbank]','[LabAnalyze]')
$parts=[Collections.Generic.List[string]]::new()
$sourceBindings=[Collections.Generic.List[object]]::new()
$part=$prefix
foreach ($section in $sections) {
    $relative=$section.Groups['path'].Value
    $source=Join-Path $repositoryRoot $relative
    if (-not (Test-Path -LiteralPath $source -PathType Leaf)) { throw 'OPS005_CANONICAL_SOURCE_MISSING' }
    $sourceBindings.Add([ordered]@{Path=$relative;Sha256=(Get-FileHash -LiteralPath $source -Algorithm SHA256).Hash.ToLowerInvariant()})
    $body=$section.Value.Replace('[DeineDatenbank]','[LabAnalyze]')+"`n"
    if ($relative -ceq 'Code/01_Common/030_VW_AnalyseAccessPolicy.sql') {
        # Der bestehende Windows-Transport erkennt diese Beispielzeile als GO.
        # Die enge Quellenbindung verhindert eine ungeprüfte Kommentaränderung.
        $normalized=[IO.File]::ReadAllText($source,$encoding).Replace("`r`n","`n")
        $reviewedHash=[Convert]::ToHexString([Security.Cryptography.SHA256]::HashData($encoding.GetBytes($normalized))).ToLowerInvariant()
        $exampleEnd=[regex]::new('(?m)^GO(?<eol>\r?\n)\*/')
        if ($reviewedHash -cne '5db246fd8ba80478506c2a8533022383a6aad57c4983c21f65d9535d7530bfca' -or
            $exampleEnd.Matches($body).Count -ne 1) { throw 'OPS005_POLICY_EXAMPLE_REVIEW_REQUIRED' }
        $body=$exampleEnd.Replace($body,'-- GO${eol}*/')
    }
    if ($encoding.GetByteCount($prefix+$body) -gt 3MB) { throw 'OPS005_CANONICAL_SOURCE_TOO_LARGE' }
    if ($encoding.GetByteCount($part+$body) -gt 3MB) {
        $parts.Add((Write-PrivateSql ('install-{0:D2}.sql' -f ($parts.Count+1)) $part))
        $part=$prefix
    }
    $part+=$body
}
if ($part -ne $prefix) { $parts.Add((Write-PrivateSql ('install-{0:D2}.sql' -f ($parts.Count+1)) $part)) }
foreach ($path in $parts) {
    $content=[IO.File]::ReadAllText($path,$encoding)
    if ((Get-Item -LiteralPath $path).Length -gt 4MB -or [regex]::Matches($content,'(?m)^\s*GO\s*\r?$').Count -gt 256 -or
        $content -match '(?m)^\s*:') { throw 'OPS005_WINDOWS_TRANSPORT_BOUND_EXCEEDED' }
}
$definitionSource=Join-Path $repositoryRoot 'Code/08_ServerHealth/220_USP_LinkedServerAnalysis.sql'
$definitionText=[IO.File]::ReadAllText($definitionSource,$encoding).Replace("`r`n","`n")
$match=[regex]::Match($definitionText,'(?s)(CREATE OR ALTER PROCEDURE.*)\nGO\s*\z')
if (-not $match.Success) { throw 'OPS005_CANONICAL_DEFINITION_INVALID' }
$definitionHash=[Security.Cryptography.SHA256]::HashData([Text.Encoding]::Unicode.GetBytes($match.Groups[1].Value.Trim()))
$contractSource=Join-Path $PSScriptRoot 'Scenarios/OPS-005/provider-unavailable.sql'
$contract=Write-PrivateSql 'provider-unavailable.sql' ([IO.File]::ReadAllText($contractSource,$encoding))
$prepare=Write-PrivateSql 'prepare-database.sql' @'
SET NOCOUNT ON;
SET XACT_ABORT ON;
IF @@TRANCOUNT<>0 OR TRY_CONVERT(uniqueidentifier,@OperationId) IS NULL
    THROW 54895,N'OPS005_DATABASE_OPERATION_REQUIRED',1;
IF COALESCE(CONVERT(int,SERVERPROPERTY(N'ProductMajorVersion')),0)<>17
    OR COALESCE(CONVERT(nvarchar(128),SERVERPROPERTY(N'Collation')),N'')<>N'SQL_Latin1_General_CP1_CS_AS'
    OR COALESCE(CONVERT(nvarchar(128),DATABASEPROPERTYEX(N'master',N'Collation')),N'')<>N'SQL_Latin1_General_CP1_CS_AS'
    OR COALESCE(CONVERT(nvarchar(128),DATABASEPROPERTYEX(N'tempdb',N'Collation')),N'')<>N'SQL_Latin1_General_CP1_CS_AS'
    OR COALESCE(IS_SRVROLEMEMBER(N'sysadmin'),0)<>1
    OR EXISTS(SELECT 1 FROM sys.dm_os_host_info WHERE host_platform<>N'Windows')
    OR NOT EXISTS(SELECT 1 FROM sys.dm_os_host_info WHERE host_platform=N'Windows')
    THROW 54895,N'OPS005_WINDOWS_PREREQUISITE_FAILED',2;
IF EXISTS(SELECT 1 FROM sys.databases WHERE database_id>4) OR EXISTS(SELECT 1 FROM sys.servers WHERE server_id<>0)
    THROW 54895,N'OPS005_EMPTY_OWN_RUN_REQUIRED',3;
DECLARE @OwnOperationMarker nvarchar(36)=CONVERT(nvarchar(36),TRY_CONVERT(uniqueidentifier,@OperationId));
CREATE DATABASE [LabAnalyze] COLLATE SQL_Latin1_General_CP1_CS_AS;
ALTER DATABASE [LabAnalyze] SET COMPATIBILITY_LEVEL=170;
EXEC [LabAnalyze].sys.sp_addextendedproperty @name=N'SQLANALYZE.Ops005Operation',@value=@OwnOperationMarker;
SELECT database_id AS OwnDatabaseId,CONVERT(nvarchar(33),create_date,126) AS OwnDatabaseCreated,
    CONVERT(nvarchar(128),SERVERPROPERTY(N'ProductVersion')) AS ProductVersion,
    CONVERT(nvarchar(128),SERVERPROPERTY(N'Edition')) AS Edition,
    collation_name AS DatabaseCollation,compatibility_level AS CompatibilityLevel
FROM sys.databases WHERE name=N'LabAnalyze';
'@
$cleanup=Write-PrivateSql 'cleanup-database.sql' @'
SET NOCOUNT ON;
IF @@TRANCOUNT<>0 OR TRY_CONVERT(uniqueidentifier,@OperationId) IS NULL
    THROW 54895,N'OPS005_DATABASE_CLEANUP_OPERATION_REQUIRED',4;
IF COALESCE(DB_ID(N'LabAnalyze'),0)<>@OwnDatabaseId
    OR NOT EXISTS(SELECT 1 FROM sys.databases WHERE database_id=@OwnDatabaseId
        AND create_date=TRY_CONVERT(datetime,@OwnDatabaseCreated,126))
    OR COALESCE(CONVERT(nvarchar(36),(SELECT value FROM [LabAnalyze].sys.extended_properties
        WHERE class=0 AND major_id=0 AND minor_id=0 AND name=N'SQLANALYZE.Ops005Operation')),N'')<>CONVERT(nvarchar(36),TRY_CONVERT(uniqueidentifier,@OperationId))
    THROW 54895,N'OPS005_DATABASE_CLEANUP_IDENTITY_LOST',5;
DROP DATABASE [LabAnalyze];
IF DB_ID(N'LabAnalyze') IS NOT NULL
    THROW 54895,N'OPS005_DATABASE_CLEANUP_FAILED',6;
SELECT N'REMOVED' AS DatabaseCleanup;
'@
$inputs=@($prepare)+@($parts)+@($contract,$cleanup)
$binding=[ordered]@{
    Scope='OPS005_WINDOWS_PROVIDER_PREPARATION';Outcome='NOT_EXECUTED';SourceHead=$head
    OperationId=$OperationId.ToString('D');Database='LabAnalyze'
    ExpectedDefinitionSha256=[Convert]::ToHexString($definitionHash).ToLowerInvariant()
    CanonicalSourceCount=$sections.Count;CanonicalSources=@($sourceBindings)
    Inputs=@($inputs | ForEach-Object { [ordered]@{Name=[IO.Path]::GetFileName($_);Bytes=(Get-Item -LiteralPath $_).Length;Sha256=(Get-FileHash -LiteralPath $_ -Algorithm SHA256).Hash.ToLowerInvariant()} })
    Bounds=[ordered]@{NewRuns=1;NativeBlocks=1;SutCalls=5;Preprobes=1;InstallationSeconds=300;PreflightSeconds=300;AcceptanceSeconds=120}
    NativePrerequisites=@('Clean integrated Lab Main','Elevated runner','Verified prepared parent','Host capacity and existing isolated network','NotRequested/Denied activation intent','Run/Scope/VM binding')
}
[IO.File]::WriteAllText((Join-Path $destination 'preparation.json'),($binding|ConvertTo-Json -Depth 8),$encoding)
[pscustomobject]@{Scope=$binding.Scope;Outcome=$binding.Outcome;CanonicalSources=$sections.Count;InstallerParts=$parts.Count;OutputDirectory=$destination}
